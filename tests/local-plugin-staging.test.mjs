import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { stageLocalPlugin, stageFusionPlugin, fusionBuildDigest, verifyStagedFusion } from '../scripts/build-runtime.mjs';
import afterPack from '../scripts/after-pack.cjs';

test('fresh local plugin replaces the unchanged-version pnpm cache', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-local-plugin-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const plugin = path.join(root, 'plugin'), profile = path.join(root, 'profile');
  const target = path.join(profile, 'node_modules/@deepseek-harness/dsh-mathmodel');
  fs.mkdirSync(path.join(plugin, 'lib'), { recursive: true });
  fs.mkdirSync(path.join(target, 'lib'), { recursive: true });
  fs.writeFileSync(path.join(plugin, 'package.json'), JSON.stringify({ name: '@deepseek-harness/dsh-mathmodel', version: '0.1.1', main: 'lib/index.js' }));
  fs.writeFileSync(path.join(plugin, 'lib/index.js'), 'export const Config = {};');
  fs.writeFileSync(path.join(target, 'lib/index.js'), 'old cached settings registration');
  fs.writeFileSync(path.join(target, 'lib/removed.js'), 'stale removed export');
  stageLocalPlugin(profile, plugin);
  assert.equal(fs.readFileSync(path.join(target, 'lib/index.js'), 'utf8'), 'export const Config = {};');
  assert.equal(fs.existsSync(path.join(target, 'lib/removed.js')), false);
  fs.writeFileSync(path.join(plugin, 'package.json'), JSON.stringify({ name: 'foreign-plugin', main: 'lib/index.js' }));
  assert.throws(() => stageLocalPlugin(profile, plugin), /identity/);
  assert.equal(fs.readFileSync(path.join(target, 'lib/index.js'), 'utf8'), 'export const Config = {};');
});

test('Fusion staging and packaging reject stale artifacts before changing output', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-fusion-build-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const plugin = path.join(root, 'fusion'), profile = path.join(root, 'profile-web');
  const lock = path.join(root, 'fusion-build-lock.json');
  fs.mkdirSync(path.join(plugin, 'src'), { recursive: true });
  fs.mkdirSync(path.join(plugin, 'lib'), { recursive: true });
  fs.mkdirSync(path.join(plugin, 'prompts'), { recursive: true });
  fs.mkdirSync(path.join(plugin, 'contracts'), { recursive: true });
  fs.mkdirSync(path.join(plugin, 'profiles'), { recursive: true });
  fs.mkdirSync(path.join(profile, 'node_modules'), { recursive: true });
  fs.writeFileSync(path.join(plugin, 'package.json'), JSON.stringify({ name: 'dsh-model-fusion', exports: { '.': { import: './lib/dsh-model-fusion.js' } } }));
  fs.writeFileSync(path.join(plugin, 'src/index.ts'), 'export const value = 1;');
  fs.writeFileSync(path.join(plugin, 'lib/dsh-model-fusion.js'), 'export const value = 1;');
  fs.writeFileSync(path.join(plugin, 'lib/client.js'), 'export const value = 1;');
  fs.writeFileSync(path.join(plugin, 'prompts/lead.md'), 'new prompt');
  fs.writeFileSync(path.join(plugin, 'contracts/fusion.ts'), 'export type Contract = {};');
  fs.writeFileSync(path.join(plugin, 'profiles/fusion-auto.example.json'), '{}');
  fs.writeFileSync(path.join(plugin, 'cordis.patch.yml'), 'new patch');
  fs.writeFileSync(path.join(plugin, 'dshx.yml'), 'new config');
  fs.mkdirSync(path.join(plugin, 'docs'));
  for (const asset of ['LICENSE', 'README.md', 'README.en.md', 'INSTALL.md', 'INSTALL.zh.md', 'docs/COMPATIBILITY.md', 'docs/EVIDENCE.md']) {
    fs.writeFileSync(path.join(plugin, asset), asset);
  }
  const digests = fusionBuildDigest(plugin);
  fs.writeFileSync(lock, JSON.stringify(digests));
  const target = path.join(profile, 'node_modules/dsh-model-fusion');
  fs.mkdirSync(path.join(target, 'lib'), { recursive: true });
  fs.writeFileSync(path.join(target, 'lib/stale.js'), 'cached');
  stageFusionPlugin(profile, plugin, lock);
  verifyStagedFusion(profile, plugin, lock);
  assert.equal(fs.existsSync(path.join(target, 'lib/stale.js')), false);
  assert.equal(fs.readFileSync(path.join(target, 'prompts/lead.md'), 'utf8'), 'new prompt');
  assert.equal(fs.readFileSync(path.join(target, 'contracts/fusion.ts'), 'utf8'), 'export type Contract = {};');
  assert.equal(fs.readFileSync(path.join(target, 'cordis.patch.yml'), 'utf8'), 'new patch');
  assert.equal(fs.readFileSync(path.join(target, 'LICENSE'), 'utf8'), 'LICENSE');
  assert.equal(fs.readFileSync(path.join(target, 'docs/EVIDENCE.md'), 'utf8'), 'docs/EVIDENCE.md');
  const packaged = path.join(root, 'packaged');
  const outputMarker = path.join(packaged, 'resources/runtime/host/keep.txt');
  fs.mkdirSync(path.dirname(outputMarker), { recursive: true });
  fs.writeFileSync(outputMarker, 'unchanged');
  const context = { electronPlatformName: 'win32', arch: 1, appOutDir: packaged };
  const rejectsWithoutCopy = async pattern => {
    await assert.rejects(afterPack.copyStagedRuntime(context, root, plugin, lock), pattern);
    assert.equal(fs.readFileSync(outputMarker, 'utf8'), 'unchanged');
  };
  fs.writeFileSync(path.join(plugin, 'src/index.ts'), 'export const value = 2;');
  assert.throws(() => stageFusionPlugin(profile, plugin, lock), /Fusion source\/lib.*mismatch/);
  await rejectsWithoutCopy(/Fusion source\/lib.*mismatch/);
  assert.equal(fs.readFileSync(path.join(target, 'lib/dsh-model-fusion.js'), 'utf8'), 'export const value = 1;');
  fs.writeFileSync(path.join(plugin, 'src/index.ts'), 'export const value = 1;');
  fs.writeFileSync(path.join(plugin, 'lib/dsh-model-fusion.js'), 'export const value = 2;');
  assert.throws(() => stageFusionPlugin(profile, plugin, lock), /Fusion source\/lib.*mismatch/);
  fs.writeFileSync(path.join(plugin, 'lib/dsh-model-fusion.js'), 'export const value = 1;');
  fs.writeFileSync(path.join(target, 'lib/dsh-model-fusion.js'), 'stale built output');
  await rejectsWithoutCopy(/Staged Fusion runtime asset mismatch: lib/);
  fs.writeFileSync(path.join(target, 'lib/dsh-model-fusion.js'), 'export const value = 1;');
  fs.rmSync(path.join(target, 'prompts/lead.md'));
  await rejectsWithoutCopy(/Staged Fusion runtime asset mismatch: prompts/);
  fs.writeFileSync(path.join(target, 'prompts/lead.md'), 'new prompt');
  const outside = path.join(root, 'outside');
  fs.mkdirSync(outside);
  fs.writeFileSync(path.join(outside, 'keep.txt'), 'outside');
  fs.rmSync(target, { recursive: true });
  fs.symlinkSync(outside, target, process.platform === 'win32' ? 'junction' : 'dir');
  assert.throws(() => stageFusionPlugin(profile, plugin, lock), /Unsafe staged Fusion plugin/);
  await rejectsWithoutCopy(/Missing or unsafe staged Fusion plugin/);
  assert.equal(fs.readFileSync(path.join(outside, 'keep.txt'), 'utf8'), 'outside');
});
