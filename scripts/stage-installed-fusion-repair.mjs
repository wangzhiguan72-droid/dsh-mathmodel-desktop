import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { randomUUID, createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const require = createRequire(import.meta.url);
const updates = require('../src/desktop-updates.cjs');
const root = path.resolve('dist/fusion-installed-verification');
const release = path.resolve(process.argv[2] ?? 'dist/fusion-release-closure-20261012-final');
const installDir = path.join(process.env.LOCALAPPDATA, 'Programs/dsh-mathmodel-desktop');
const stage = path.join(path.dirname(installDir), `.dsh-fusion-repair-${randomUUID()}`);
const zip = path.join(release, 'dsh-mathmodel-desktop-0.1.3-win-x64.zip');
const receipt = JSON.parse(fs.readFileSync(path.join(release, 'verification.json')));
const digest = filename => createHash('sha256').update(fs.readFileSync(filename)).digest('hex');
if (digest(zip) !== receipt.artifactSha256[path.basename(zip)]) throw new Error('ZIP digest changed');
const archive = updates.inspectZip(zip, { includeEntries: true });
fs.mkdirSync(stage);
console.log('Extracting validated ZIP to a fresh installation sibling');
execFileSync(path.join(process.env.SystemRoot, 'System32/tar.exe'), ['-xf', zip, '-C', stage], { windowsHide: true, timeout: 1200000 });
updates.verifyExtractedZip(stage, archive);
updates.validateCandidate(stage, { executableName: 'DeepSeek 数学建模版.exe', packageName: 'dsh-mathmodel-desktop', version: '0.1.3' });
const nsis = path.join(release, 'dsh-mathmodel-desktop-0.1.3-win-x64.exe');
if (digest(nsis) !== receipt.artifactSha256[path.basename(nsis)]) throw new Error('NSIS digest changed');
const unpacker = path.resolve('node_modules/electron-winstaller/vendor/7z-x64.exe');
const uninstallStage = path.join(root, `candidate-uninstaller-${randomUUID()}`);
fs.mkdirSync(uninstallStage);
execFileSync(unpacker, ['e', '-y', `-o${uninstallStage}`, nsis, '-ir!$R9\\Uninstall*.exe'], { windowsHide: true, timeout: 300000, stdio: 'pipe' });
const uninstallers = fs.readdirSync(uninstallStage).filter(name => /^Uninstall .+\.exe$/i.test(name));
if (uninstallers.length !== 1) throw new Error('Candidate uninstaller is ambiguous');
fs.copyFileSync(path.join(uninstallStage, uninstallers[0]), path.join(stage, uninstallers[0]));
const stagedReceipt = { stage, installDir, zipSha256: digest(zip), appAsarSha256: digest(path.join(stage, 'resources/app.asar')), uninstallerSha256: digest(path.join(stage, uninstallers[0])), extractedFiles: archive.entries.length, ready: true };
fs.writeFileSync(path.join(root, 'zip-repair-stage.json'), JSON.stringify(stagedReceipt, null, 2));
console.log(JSON.stringify(stagedReceipt));
